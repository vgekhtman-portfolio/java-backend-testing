package com.vgekhtman.automation.tests.contract.provider;

import au.com.dius.pact.provider.junit5.HttpTestTarget;
import au.com.dius.pact.provider.junit5.PactVerificationContext;
import au.com.dius.pact.provider.junit5.PactVerificationInvocationContextProvider;
import au.com.dius.pact.provider.junitsupport.Provider;
import au.com.dius.pact.provider.junitsupport.State;
import au.com.dius.pact.provider.junitsupport.loader.PactFolder;
import com.vgekhtman.automation.tests.contract.PactFiles;
import com.vgekhtman.automation.testutils.CustomSut;
import com.vgekhtman.automation.testutils.CustomSutExtension;
import io.qameta.allure.Allure;
import io.qameta.allure.Epic;
import io.qameta.allure.Feature;
import io.qameta.allure.Story;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Order;
import org.junit.jupiter.api.Tag;
import org.junit.jupiter.api.TestTemplate;
import org.junit.jupiter.api.extension.ExtendWith;

import java.net.URI;
import java.time.OffsetDateTime;
import java.util.Map;
import java.util.UUID;

/**
 * Replays the pact generated by the consumer test against the real, running orders-service - a genuine
 * verification of live behaviour, not a mock. Each interaction's provider state is established by writing
 * to the service's Postgres directly, so the database holds exactly what the consumer's expectation assumes.
 */
@Epic("API Protocols")
@Feature("Contract (Pact)")
@Story("Provider verification")
@Tag("custom-sut")
@Order(2)
@Provider("orders-service")
@PactFolder(PactFiles.DIR)
@ExtendWith(CustomSutExtension.class)
class OrdersProviderVerificationTest {

    /**
     * The target has to be set before the extension starts the interaction, so it can't move into the
     * template method. The {@code PactVerificationContext} parameter is supplied by the Pact extension
     * registered on that method; the IDE's static check doesn't see that and flags it.
     */
    @BeforeEach
    @SuppressWarnings("JUnitMalformedDeclaration")
    void pointAtTheRunningService(PactVerificationContext context) {
        URI service = URI.create(CustomSut.restBaseUrl());
        context.setTarget(new HttpTestTarget(service.getHost(), service.getPort()));
    }

    /**
     * One invocation per interaction in the pact. The interaction description starts with the scenario ID
     * ("TC-PACT-004: a request to create an order"), which names the Allure test.
     */
    @TestTemplate
    @ExtendWith(PactVerificationInvocationContextProvider.class)
    void verifyInteraction(PactVerificationContext context) {
        String description = context.getInteraction().getDescription();
        String id = description.substring(0, description.indexOf(": "));
        String interaction = description.substring(id.length() + 2);
        Allure.getLifecycle().updateTest(test -> test
                .setName(id + ": provider: " + interaction)
                .setDescription("The real orders-service answers the pact interaction \"" + interaction
                        + "\" as the consumer declared it; provider states are set up by writing to Postgres directly."));
        context.verifyInteraction();
    }

    @State("an order exists")
    void anOrderExists(Map<String, Object> params) {
        ProviderStateDb.putOrder(
                UUID.fromString((String) params.get("id")),
                (String) params.get("customerId"),
                (String) params.get("productId"),
                ((Number) params.get("quantity")).intValue(),
                (String) params.get("status"),
                OffsetDateTime.parse((String) params.get("createdAt")));
    }

    @State("no order exists")
    void noOrderExists(Map<String, Object> params) {
        ProviderStateDb.deleteOrder(UUID.fromString((String) params.get("id")));
    }
}
